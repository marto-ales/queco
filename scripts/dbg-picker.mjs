import puppeteer from "puppeteer-core";
const browser = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", headless: "new", args: ["--no-sandbox"] });
const page = await browser.newPage();
await page.goto("http://localhost:3456/planner", { waitUntil: "networkidle0" });
await page.$$eval("button", (btns) => btns.find((x) => x.textContent.trim() === "+ Almuerzo").click());
await page.waitForSelector('div[role="dialog"] input[placeholder="Buscar receta..."]', { visible: true });
await page.click('div[role="dialog"] input[type="checkbox"]');
const checked = await page.$eval('div[role="dialog"] input[type="checkbox"]', (e) => e.checked);
console.log("checkbox after click:", checked);
await page.type('div[role="dialog"] input[placeholder="Buscar receta..."]', "sopa");
await new Promise((r) => setTimeout(r, 400));
console.log("search value:", await page.$eval('div[role="dialog"] input[placeholder="Buscar receta..."]', (e) => e.value));
console.log("span rows:", await page.$$eval('div[role="dialog"] button span.text-2xl', (e) => e.length));
console.log("dialog text:", (await page.$eval('div[role="dialog"]', (e) => e.innerText)).slice(0, 300));
await browser.close();
